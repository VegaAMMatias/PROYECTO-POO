private void cargarTablaHabitaciones() {
    DefaultTableModel modelo = (DefaultTableModel) tblHabitaciones.getModel();
    modelo.setRowCount(0); 

    if (sistema == null) {
        return;
    }

    Habitacion[] habs = sistema.getHabitaciones();
    if (habs == null) {
        return;
    }

    for (Habitacion h : habs) {
        if (h != null) {
            Object[] fila = new Object[] {
                h.getNumero(),
                h.getTipo(), 
                h.getCapacidadMax(), 
                h.getPrecioNoche(), 
                h.getEstado(),        
                "ACTIVA"             
            };
            modelo.addRow(fila);
        }
    }
}
public GestionDeHabitaciones(SistemaHotel sistema) {
    this.sistema = sistema;
    initComponents();
    setLocationRelativeTo(null);
    cargarTablaHabitaciones();   
}


