    private void btnEditarHabitacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarHabitacionActionPerformed
    int fila = tblHabitaciones.getSelectedRow();
    
    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Seleccione una habitación de la tabla.",
                "Aviso",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Primera columna: número de habitación
    String numero = (String) tblHabitaciones.getValueAt(fila, 0);

    // Por ahora solo enviamos el número a la ventana de edición
javax.swing.JOptionPane.showMessageDialog(
        this,
        "Aquí se abriría la ventana para editar la habitación N° " + numero,
        "Editar habitación",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
);
    }//GEN-LAST:event_btnEditarHabitacionActionPerformed

    private void btnDesactivarHabitacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDesactivarHabitacionActionPerformed
    int fila = tblHabitaciones.getSelectedRow();
    
    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Seleccione una habitación para desactivarla.",
                "Aviso",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String numero = (String) tblHabitaciones.getValueAt(fila, 0);

    // Más adelante: buscar la habitación en SistemaHotel y marcarla como inactiva
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Aquí se marcaría como INACTIVA la habitación N° " + numero,
            "Desactivar habitación",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
    );
    }//GEN-LAST:event_btnDesactivarHabitacionActionPerformed

    private void btnBuscarHabitacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarHabitacionActionPerformed
    String texto = txtBuscarHabitacion.getText().trim();

    if (texto.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Ingrese un número o tipo de habitación para buscar.",
                "Aviso",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Más adelante filtraremos la tabla usando SistemaHotel
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Aquí se filtraría la tabla de habitaciones usando: " + texto,
            "Buscar habitación",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
    );
    }//GEN-LAST:event_btnBuscarHabitacionActionPerformed

